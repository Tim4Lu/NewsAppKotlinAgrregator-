        Дослідники NASA розробили підхід, що дозволяє знаходити екзопланети у 5 разів швидше. Технологія аналізує спектральні коливання зірок.

        • Точність виявлення зросла з 60% до 92%
        • Тестування проходить на телескопі James Webb
        • Результати опубліковані в Nature Astronomy

        Виводь ЛИШЕ готовий текст поста. Без пояснень, без преамбули, без повторення інструкцій.
