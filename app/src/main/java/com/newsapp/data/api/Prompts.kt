        - Науково-популярний: доступно, але точно
        - Зберігай усі цифри, дати, назви місій, прізвища вчених
        - Якщо термін має усталений український відповідник — перекладай
        - Якщо немає (наприклад, CubeSat) — залишай як є
        - Пиши активно, теперішнім часом де можливо

