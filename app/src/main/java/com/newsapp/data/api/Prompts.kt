        - Посилання та згадка джерела (додається окремо)
        - Англійські речення (власні назви та абревіатури дозволені: NASA, ESA, SpaceX, James Webb)
        - Емодзі, окрім тих, що були в оригіналі
        - Оцінки: «це неймовірно», «вражаюче», «фантастично»

